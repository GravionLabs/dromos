//! Generates `crates/dromos-mux-proto/src/generated.rs` from `schema/events.schema.json`.
//!
//! Run with `cargo run -p dromos-schema-gen --locked`. The output is deterministic so CI can
//! regenerate it and diff against the checked-in file.
//!
//! Before handing the schema to typify it is normalised (see [`normalize`]) so typify emits an
//! internally tagged `BusEvent` enum and keeps timestamps as validated strings.

use std::collections::BTreeSet;
use std::fmt;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use serde_json::{Map, Value};
use typify::{TypeSpace, TypeSpaceSettings};

/// First line of the generated module.
const HEADER: &str =
    "// @generated by dromos-schema-gen from schema/events.schema.json. Do not edit.\n\n";

/// Errors that can occur while turning the JSON Schema into Rust source.
#[derive(Debug)]
enum GenError {
    /// The input is not a valid JSON Schema document.
    Schema(serde_json::Error),
    /// typify rejected the schema.
    Typify(typify::Error),
    /// typify produced tokens that do not parse as a Rust file.
    Syntax(syn::Error),
}

impl fmt::Display for GenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Schema(e) => write!(f, "invalid JSON Schema: {e}"),
            Self::Typify(e) => write!(f, "typify failed: {e}"),
            Self::Syntax(e) => write!(f, "generated code does not parse: {e}"),
        }
    }
}

/// Rewrites the Zod-exported schema into a shape typify maps to idiomatic Rust.
///
/// - `const: v` becomes `enum: [v]`: typify only recognises single-value enums as the fixed
///   discriminator of an internally tagged enum.
/// - `$ref` entries of a `oneOf` are inlined: typify does not resolve references when looking for
///   the tag. Definitions referenced only from such a `oneOf` are dropped afterwards.
/// - `format: date-time` is removed so timestamps stay strings validated by their `pattern`;
///   chrono would re-serialise `09:15:30.000Z` as `09:15:30Z` and break the wire format.
fn normalize(schema: &mut Value) {
    rewrite_keywords(schema);

    let Some(defs) = schema
        .get("definitions")
        .and_then(Value::as_object)
        .cloned()
    else {
        return;
    };
    let mut inlined = BTreeSet::new();
    inline_one_of_refs(schema, &defs, &mut inlined);

    let referenced = collect_refs(schema);
    if let Some(defs) = schema.get_mut("definitions").and_then(Value::as_object_mut) {
        for name in inlined {
            if !referenced.contains(&format!("{DEF_PREFIX}{name}")) {
                defs.remove(&name);
            }
        }
    }
}

/// Prefix of local definition references.
const DEF_PREFIX: &str = "#/definitions/";

fn rewrite_keywords(value: &mut Value) {
    match value {
        Value::Object(map) => {
            if let Some(constant) = map.remove("const") {
                map.insert("enum".to_owned(), Value::Array(vec![constant]));
            }
            if map.get("format").and_then(Value::as_str) == Some("date-time") {
                map.remove("format");
            }
            for (key, child) in map.iter_mut() {
                match (key.as_str(), child) {
                    // Keys of these maps are names, not keywords: only rewrite their schemas.
                    ("properties" | "definitions" | "patternProperties", Value::Object(named)) => {
                        named.values_mut().for_each(rewrite_keywords);
                    }
                    (_, child) => rewrite_keywords(child),
                }
            }
        }
        Value::Array(items) => items.iter_mut().for_each(rewrite_keywords),
        _ => {}
    }
}

fn inline_one_of_refs(
    value: &mut Value,
    defs: &Map<String, Value>,
    inlined: &mut BTreeSet<String>,
) {
    match value {
        Value::Object(map) => {
            if let Some(Value::Array(variants)) = map.get_mut("oneOf") {
                for variant in variants.iter_mut() {
                    let target = variant
                        .as_object()
                        .filter(|v| v.len() == 1)
                        .and_then(|v| v.get("$ref"))
                        .and_then(Value::as_str)
                        .and_then(|r| r.strip_prefix(DEF_PREFIX))
                        .map(str::to_owned);
                    if let Some(name) = target
                        && let Some(def) = defs.get(&name)
                    {
                        *variant = def.clone();
                        inlined.insert(name);
                    }
                }
            }
            for v in map.values_mut() {
                inline_one_of_refs(v, defs, inlined);
            }
        }
        Value::Array(items) => {
            for v in items {
                inline_one_of_refs(v, defs, inlined);
            }
        }
        _ => {}
    }
}

fn collect_refs(value: &Value) -> BTreeSet<String> {
    let mut refs = BTreeSet::new();
    let mut stack = vec![value];
    while let Some(v) = stack.pop() {
        match v {
            Value::Object(map) => {
                if let Some(r) = map.get("$ref").and_then(Value::as_str) {
                    refs.insert(r.to_owned());
                }
                stack.extend(map.values());
            }
            Value::Array(items) => stack.extend(items),
            _ => {}
        }
    }
    refs
}

/// Converts a JSON Schema document into formatted Rust source with the `@generated` header.
fn generate(schema_json: &str) -> Result<String, GenError> {
    let mut raw: Value = serde_json::from_str(schema_json).map_err(GenError::Schema)?;
    normalize(&mut raw);
    let schema: schemars::schema::RootSchema =
        serde_json::from_value(raw).map_err(GenError::Schema)?;

    let mut settings = TypeSpaceSettings::default();
    settings
        .with_struct_builder(false)
        .with_derive("PartialEq".to_owned());
    let mut space = TypeSpace::new(&settings);
    space.add_root_schema(schema).map_err(GenError::Typify)?;

    let file = syn::parse2::<syn::File>(space.to_stream()).map_err(GenError::Syntax)?;
    Ok(format!("{HEADER}{}", prettyplease::unparse(&file)))
}

/// Workspace root, derived from this crate's manifest directory.
fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn main() -> ExitCode {
    let root = workspace_root();
    let input = root.join("schema/events.schema.json");
    let output = root.join("crates/dromos-mux-proto/src/generated.rs");

    let schema_json = match fs::read_to_string(&input) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("cannot read {}: {e}", input.display());
            return ExitCode::FAILURE;
        }
    };
    let code = match generate(&schema_json) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("{e}");
            return ExitCode::FAILURE;
        }
    };
    if let Err(e) = fs::write(&output, code) {
        eprintln!("cannot write {}: {e}", output.display());
        return ExitCode::FAILURE;
    }
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn checked_in_module_matches_schema() {
        let root = workspace_root();
        let schema = fs::read_to_string(root.join("schema/events.schema.json")).unwrap();
        let checked_in =
            fs::read_to_string(root.join("crates/dromos-mux-proto/src/generated.rs")).unwrap();
        assert!(
            generate(&schema).unwrap() == checked_in,
            "generated.rs is stale; run `cargo run -p dromos-schema-gen --locked`"
        );
    }

    #[test]
    fn output_is_deterministic() {
        let schema =
            fs::read_to_string(workspace_root().join("schema/events.schema.json")).unwrap();
        assert_eq!(generate(&schema).unwrap(), generate(&schema).unwrap());
    }

    #[test]
    fn output_starts_with_generated_header() {
        let schema = r#"{"definitions":{"Ping":{"type":"object","properties":{"n":{"type":"integer"}},"required":["n"]}}}"#;
        let code = generate(schema).unwrap();
        assert!(code.starts_with(
            "// @generated by dromos-schema-gen from schema/events.schema.json. Do not edit.\n"
        ));
        assert!(code.contains("pub struct Ping"));
    }

    #[test]
    fn rejects_non_json_input() {
        assert!(matches!(generate("not json"), Err(GenError::Schema(_))));
    }

    #[test]
    fn normalize_turns_const_into_single_value_enum() {
        let mut schema = json!({"type": "string", "const": "hook:idle"});
        normalize(&mut schema);
        assert_eq!(schema, json!({"type": "string", "enum": ["hook:idle"]}));
    }

    #[test]
    fn normalize_drops_date_time_format_but_keeps_pattern() {
        let mut schema = json!({"type": "string", "format": "date-time", "pattern": "^x$"});
        normalize(&mut schema);
        assert_eq!(schema, json!({"type": "string", "pattern": "^x$"}));
    }

    #[test]
    fn normalize_does_not_treat_property_names_as_keywords() {
        let mut schema = json!({"type": "object", "properties": {
            "const": {"type": "string"},
            "format": {"type": "string", "const": "x"}
        }});
        normalize(&mut schema);
        assert_eq!(
            schema,
            json!({"type": "object", "properties": {
                "const": {"type": "string"},
                "format": {"type": "string", "enum": ["x"]}
            }})
        );
    }

    #[test]
    fn normalize_keeps_other_formats() {
        let mut schema = json!({"type": "string", "format": "uuid"});
        normalize(&mut schema);
        assert_eq!(schema, json!({"type": "string", "format": "uuid"}));
    }

    #[test]
    fn normalize_inlines_one_of_refs_and_drops_only_unreferenced_definitions() {
        let mut schema = json!({
            "$ref": "#/definitions/Union",
            "definitions": {
                "Union": {"oneOf": [{"$ref": "#/definitions/A"}, {"$ref": "#/definitions/B"}]},
                "A": {"type": "object", "properties": {"b": {"$ref": "#/definitions/B"}}},
                "B": {"type": "object"}
            }
        });
        normalize(&mut schema);
        assert_eq!(
            schema,
            json!({
                "$ref": "#/definitions/Union",
                "definitions": {
                    "Union": {"oneOf": [
                        {"type": "object", "properties": {"b": {"$ref": "#/definitions/B"}}},
                        {"type": "object"}
                    ]},
                    "B": {"type": "object"}
                }
            })
        );
    }

    #[test]
    fn normalize_leaves_schema_without_definitions_alone() {
        let mut schema = json!({"oneOf": [{"$ref": "#/definitions/Missing"}]});
        normalize(&mut schema);
        assert_eq!(
            schema,
            json!({"oneOf": [{"$ref": "#/definitions/Missing"}]})
        );
    }

    #[test]
    fn const_discriminated_one_of_becomes_internally_tagged_enum() {
        let schema = r##"{
            "$ref": "#/definitions/Ev",
            "definitions": {
                "Ev": {"oneOf": [{"$ref": "#/definitions/A"}, {"$ref": "#/definitions/B"}]},
                "A": {"type": "object", "properties": {"type": {"type": "string", "const": "a"}},
                      "required": ["type"], "additionalProperties": false},
                "B": {"type": "object", "properties": {"type": {"type": "string", "const": "b"}},
                      "required": ["type"], "additionalProperties": false}
            }
        }"##;
        let code = generate(schema).unwrap();
        assert!(code.contains("#[serde(tag = \"type\""), "{code}");
        assert!(code.contains("pub enum Ev"), "{code}");
    }
}
